def process_all_pages():
    total_diagrams_retained = 0
    total_pages_updated = 0
    
    for pfile in sorted(cache_dir.glob("page_*.json")):
        data = json.loads(pfile.read_text(encoding="utf-8"))
        pno = data["page_no"]
        ch_no = data["chapter_no"]
        ch_str = f"ch_{ch_no:02d}"
        
        # Clean text
        raw_md = data["markdown"]
        cleaned_md = clean_bangla_ocr(raw_md)
        
        # Filter and assign verified captions to diagrams
        cleaned_diagrams = []
        for d in data.get("diagrams", []):
            fid = d["figure_id"]
            if fid in FORMULA_AND_TEXT_BOXES:
                # Discard from diagram list
                continue
                
            # If we have a verified authentic caption, use it!
            if fid in FIGURE_CAPTIONS:
                d["caption"] = FIGURE_CAPTIONS[fid]
            elif "বিজ্ঞান বিষয়ক চিত্র" in d["caption"]:
                # If still generic, create a meaningful context caption
                d["caption"] = f"অধ্যায় {ch_no:02d} চিত্র: বৈজ্ঞানিক রেখাচিত্র (পৃষ্ঠা {pno})"
                
            # Ensure local_path exists
            target_path = Path("/home/syed/workspace/Sheratutor") / d["local_path"]
            if target_path.exists():
                cleaned_diagrams.append(d)
                total_diagrams_retained += 1
                
        # Re-sync diagram markers in markdown
        # Remove old [DIAGRAM: ...] markers
        cleaned_md = re.sub(r"\[DIAGRAM:[^\]]*\]\n*", "", cleaned_md).strip()
        
        # Prepend clean diagram markers if diagrams present
        if cleaned_diagrams:
            markers = "\n".join([f"[DIAGRAM: {d['caption']}]" for d in cleaned_diagrams])
            cleaned_md = f"{markers}\n\n{cleaned_md}"
            
        data["markdown"] = cleaned_md
        data["diagrams"] = cleaned_diagrams
        data["verified"] = True
        
        pfile.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
        total_pages_updated += 1

    print(f"SUCCESS: Processed all {total_pages_updated} pages!")
    print(f"Total Authentic Scientific Diagrams Retained: {total_diagrams_retained}")

if __name__ == "__main__":
    process_all_pages()
