def clean_bangla_ocr(text: str) -> str:
    cleaned = text
    for pattern, repl in REPLACEMENTS:
        cleaned = re.sub(pattern, repl, cleaned)
        
    # Standardize reaction arrows
    cleaned = re.sub(r"\s*(-->|—>|—o|-৯|->|—\s*৯)\s*", " $\\rightarrow$ ", cleaned)
    
    # Standardize Delta H OCR misreadings
    cleaned = re.sub(r"\b(AW|AH)\s*=\s*", r"$\\Delta H$ = ", cleaned)
    
    return cleaned
